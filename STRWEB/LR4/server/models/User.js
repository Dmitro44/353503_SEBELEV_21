const mongoose = require('mongoose');
const Schema = mongoose.Schema;

const UserSchema = new Schema({
    name: {
        type: String,
        required: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    },
    role: {
        type: String,
        enum: ['customer', 'admin'],
        default: 'customer'
    },
    rentalHistory: [{
        type: Schema.Types.ObjectId,
        ref: 'Rental'
    }]
}, { timestamps: true });

module.exports = mongoose.model('User', UserSchema);
